"""Push the brief into installed agents and register the shared MCP server.

Managed instruction blocks and agent configs are backed up before the first edit.
"""
from __future__ import annotations

import hashlib
import json
import re
import shlex
import shutil
from pathlib import Path

from .security import private_dir, private_write
from .core import BUILD, HOME, ROOT, STATE, log, user_name

START, END = "<!-- metaharness:start -->", "<!-- metaharness:end -->"
SKILL_MARKER = "<!-- generated by metaharness -->"
REPO = Path(__file__).resolve().parent.parent
MH = str(REPO / "mh")
TARGETS = {
    "claude-code": HOME / ".claude" / "CLAUDE.md",
    "codex": HOME / ".codex" / "AGENTS.md",
    "gemini+antigravity": HOME / ".gemini" / "GEMINI.md",
}


def _backup(p: Path) -> None:
    key = hashlib.sha256(str(p).encode()).hexdigest()[:16]
    dest = STATE / "backups" / f"{p.name}.{key}.orig"
    if p.exists() and not dest.exists():
        STATE.mkdir(parents=True, exist_ok=True, mode=0o700)
        dest.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        shutil.copy2(p, dest)
        dest.chmod(0o600)


def _block_pattern(text: str) -> re.Pattern:
    if text.count(START) != text.count(END):
        raise ValueError("unbalanced Metaharness markers; leaving file unchanged")
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if len(pattern.findall(text)) != text.count(START):
        raise ValueError("invalid Metaharness markers; leaving file unchanged")
    return pattern


def upsert_block(p: Path, body: str) -> bool:
    old = p.read_text() if p.exists() else ""
    pattern = _block_pattern(old)
    body = body.replace(START, "&lt;!-- metaharness:start --&gt;").replace(END, "&lt;!-- metaharness:end --&gt;")
    block = f"{START}\n{body.strip()}\n{END}"
    new = pattern.sub(lambda _: block, old) if pattern.search(old) else old + ("\n\n" if old else "") + block + "\n"
    if new == old:
        if p.exists():
            p.chmod(0o600)
        return False
    _backup(p)
    private_dir(p.parent)
    p.write_text(new)
    p.chmod(0o600)
    return True


def remove_block(p: Path) -> bool:
    if not p.exists():
        return False
    old = p.read_text()
    new = _block_pattern(old).sub("", old)
    if new == old:
        if p.exists():
            p.chmod(0o600)
        return False
    _backup(p)
    p.write_text(new)
    p.chmod(0o600)
    return True


def installed() -> dict[str, bool]:
    return {
        "claude-code": (HOME / ".claude").is_dir() or (HOME / ".claude.json").is_file() or bool(shutil.which("claude")),
        "codex": (HOME / ".codex").is_dir() or bool(shutil.which("codex")),
        "gemini-cli": (HOME / ".gemini" / "settings.json").is_file() or bool(shutil.which("gemini")),
        "antigravity": (HOME / ".gemini" / "antigravity").is_dir() or bool(shutil.which("antigravity")),
    }


def sync(brief: str) -> list[str]:
    agents = installed()
    agents["gemini+antigravity"] = agents["gemini-cli"] or agents["antigravity"] or (HOME / ".gemini" / "GEMINI.md").exists()
    changed = []
    for name, path in TARGETS.items():
        if agents[name] and upsert_block(path, brief):
            changed.append(name)
    if changed:
        log(f"sync wrote: {', '.join(changed)}")
    return changed


def unsync() -> list[str]:
    return [name for name, path in TARGETS.items() if remove_block(path)]


def _json_mcp(path: Path) -> str:
    raw = path.read_text().strip() if path.exists() else ""
    data = json.loads(raw) if raw else {}
    if not isinstance(data, dict) or not isinstance(data.get("mcpServers", {}), dict):
        raise ValueError("expected an object with an mcpServers object")
    servers = data.setdefault("mcpServers", {})
    want = {"command": MH, "args": ["mcp"], "env": {"MH_HOME": str(ROOT)}}
    if servers.get("metaharness") == want:
        return "already"
    _backup(path)
    servers["metaharness"] = want
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n")
    path.chmod(0o600)
    return "added"


def _codex_toml() -> str:
    path = HOME / ".codex" / "config.toml"
    old = path.read_text() if path.exists() else ""
    # Preserve unfamiliar valid TOML representations instead of guessing edits.
    try:
        import tomllib
    except ImportError:
        raise ValueError("Python 3.11+ is required to safely edit Codex TOML; configure its MCP manually")
    original = tomllib.loads(old)
    if '"""' in old or "'" * 3 in old:
        raise ValueError("multiline TOML requires manual MCP configuration; file left unchanged")
    section = ("[mcp_servers.metaharness]\n" + f"command = {json.dumps(MH)}\n" +
               'args = ["mcp"]\n\n[mcp_servers.metaharness.env]\n' + f"MH_HOME = {json.dumps(str(ROOT))}\n")
    pattern = re.compile(r'''^[ \t]*\[mcp_servers\.(?:metaharness|"metaharness"|'metaharness')(?:\.[^\]]+)?\][ \t]*(?:\#[^\n]*)?(?:\n|\Z).*?(?=^[ \t]*\[|\Z)''', re.M | re.S)
    remaining = pattern.sub("", old)
    new = remaining.rstrip() + ("\n\n" if remaining.strip() else "") + section
    parsed = tomllib.loads(new)
    original_servers = original.get("mcp_servers", {})
    if not isinstance(original_servers, dict):
        raise ValueError("invalid MCP configuration")
    expected = {**original, "mcp_servers": {**original_servers, "metaharness": parsed["mcp_servers"]["metaharness"]}}
    if parsed != expected:
        raise ValueError("unsupported TOML representation; file left unchanged")
    if new == old:
        return "already"
    _backup(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(new)
    path.chmod(0o600)
    return "added"


def install_mcp() -> dict[str, str]:
    agents = installed()
    paths = {
        "claude-code": HOME / ".claude.json",
        "gemini-cli": HOME / ".gemini" / "settings.json",
        "antigravity": HOME / ".gemini" / "antigravity" / "mcp_config.json",
    }
    result = {}
    for name, present in agents.items():
        try:
            result[name] = (_codex_toml() if name == "codex" else _json_mcp(paths[name])) if present else "skipped (not installed)"
        except (OSError, ValueError) as e:
            result[name] = f"skipped ({e})"
    log(f"install_mcp {result}")
    return result


def render_setup() -> list[str]:
    BUILD.mkdir(parents=True, exist_ok=True, mode=0o700)
    out = BUILD / "setup"
    out.mkdir(parents=True, exist_ok=True, mode=0o700)
    paths = []
    for source in sorted((REPO / "setup").glob("*.md")):
        text = source.read_text().replace("{{NAME}}", user_name()).replace("{{MH}}", shlex.quote(MH))
        path = out / source.name
        if not path.exists() or path.read_text() != text:
            private_write(path, text)
        paths.append(str(path))
    return paths


def install_skills() -> dict[str, str]:
    render_setup()
    text = (BUILD / "setup" / "know-me.SKILL.md").read_text()
    paths = {
        "claude-code": HOME / ".claude" / "skills" / "know-me" / "SKILL.md",
        "codex": HOME / ".agents" / "skills" / "know-me" / "SKILL.md",
        "gemini-cli": HOME / ".gemini" / "skills" / "know-me" / "SKILL.md",
        "antigravity": HOME / ".gemini" / "antigravity" / "skills" / "know-me" / "SKILL.md",
    }
    result = {}
    for name, present in installed().items():
        path = paths[name]
        if not present:
            result[name] = "skipped (not installed)"
        elif path.exists() and SKILL_MARKER not in path.read_text():
            result[name] = "skipped (existing know-me skill; rendered copy in build/setup)"
        elif path.exists() and path.read_text() == text:
            result[name] = "already"
        else:
            _backup(path)
            path.parent.mkdir(parents=True, exist_ok=True)
            private_write(path, text)
            result[name] = "added"
    return result
